import { id, transitiveExternals } from './diagrams.js';
import type { ArchitectureModel } from './types.js';

/** Structurizr DSL workspace with context, container and component views. */
export function renderStructurizr(model: ArchitectureModel): string {
  const q = (s: string) => `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
  const lines: string[] = [];
  const reach = transitiveExternals(model);
  const key = (n: string) => n.replace(/[^A-Za-z0-9]+/g, '_').replace(/^_|_$/g, '');
  const cmp = (pkg: string, comp: string) => `cmp_${key(pkg)}_${key(comp)}`;

  lines.push(`workspace ${q(model.name)} ${q('Generated by arch-map')} {`, '  model {', '    user = person "User"');
  lines.push(`    system = softwareSystem ${q(model.name)} {`);
  for (const c of model.containers) {
    lines.push(`      ${id('pkg', c.name)} = container ${q(c.name)} ${q(c.description ?? '')} ${q(c.technology)} {`);
    lines.push(`        tags ${q(c.kind === 'library' ? 'Library' : 'Deployable')}`);
    for (const comp of model.components.filter((x) => x.package === c.name)) {
      lines.push(`        ${cmp(c.name, comp.id)} = component ${q(comp.id)}`);
    }
    lines.push('      }');
  }
  lines.push('    }');
  for (const e of model.externals) lines.push(`    ${id('ext', e.id)} = softwareSystem ${q(e.name)} ${q(e.kind)} {`, '      tags "External"', '    }');

  for (const c of model.containers.filter((x) => x.kind === 'web' || x.kind === 'cli')) lines.push(`    user -> ${id('pkg', c.name)} "Uses"`);
  for (const e of model.edges.filter((x) => x.imports > 0 && !x.testOnly)) lines.push(`    ${id('pkg', e.from)} -> ${id('pkg', e.to)} "Imports"`);
  for (const c of model.containers) {
    for (const [ext, via] of reach.get(c.name) ?? []) {
      if (!via) lines.push(`    ${id('pkg', c.name)} -> ${id('ext', ext)} "Uses"`);
    }
  }
  for (const e of model.componentEdges) {
    lines.push(`    ${cmp(e.package, e.from)} -> ${cmp(e.package, e.to)} "Imports"`);
  }
  lines.push('  }', '', '  views {');
  lines.push('    systemContext system "Context" {', '      include *', '      autoLayout', '    }');
  lines.push('    container system "Containers" {', '      include *', '      autoLayout', '    }');
  for (const c of model.containers.filter((x) => model.components.some((k) => k.package === x.name))) {
    lines.push(`    component ${id('pkg', c.name)} ${q(`Components-${key(c.name)}`)} {`, '      include *', '      autoLayout', '    }');
  }
  lines.push(
    '    styles {',
    '      element "Person" {',
    '        shape Person',
    '        background #08427b',
    '        color #ffffff',
    '      }',
    '      element "Container" {',
    '        background #438dd5',
    '        color #ffffff',
    '      }',
    '      element "Library" {',
    '        background #85bbf0',
    '        color #000000',
    '      }',
    '      element "External" {',
    '        background #999999',
    '        color #ffffff',
    '      }',
    '    }',
    '  }',
    '}',
  );
  return lines.join('\n') + '\n';
}
