import { componentDiagram, containerDiagram, contextDiagram, packageDiagram } from './diagrams.js';
import type { ArchitectureModel, Config, Violation } from './types.js';

const KIND_LABEL = { web: 'Web app', api: 'API', worker: 'Worker', cli: 'CLI', library: 'Library' } as const;

/** The architecture document: tables and Mermaid diagrams, deterministic so it can be checked in CI. */
export function renderMarkdown(model: ArchitectureModel, config: Config, violations: Violation[]): string {
  const out: string[] = [];
  const mermaid = (src: string) => out.push('```mermaid', src, '```', '');

  out.push(`# Architecture: ${model.name}`, '');
  out.push('<!-- Generated by arch-map. Do not edit by hand: run `npx arch-map generate`. -->', '');
  out.push(
    `${model.containers.length} packages, ${model.edges.filter((e) => e.imports > 0).length} dependencies between them, ${model.externals.length} external system${model.externals.length === 1 ? '' : 's'}.`,
    '',
  );

  out.push('## System context', '');
  mermaid(contextDiagram(model));

  out.push('## Containers', '');
  out.push('| Package | Kind | Technology | Path | Description |', '| --- | --- | --- | --- | --- |');
  for (const c of model.containers) {
    out.push(`| ${cell(c.name)} | ${KIND_LABEL[c.kind]} | ${cell(c.technology)} | \`${c.dir}\` | ${cell(c.description ?? '')} |`);
  }
  out.push('');
  mermaid(containerDiagram(model));

  if (model.externals.length) {
    out.push('### External systems', '');
    out.push('| System | Kind | Detected from | Used by |', '| --- | --- | --- | --- |');
    for (const e of model.externals) {
      const users = model.containers.filter((c) => c.externals.includes(e.id)).map((c) => c.name);
      out.push(`| ${cell(e.name)} | ${e.kind} | ${e.via.map((v) => `\`${v}\``).join(', ')} | ${users.map(cell).join(', ')} |`);
    }
    out.push('');
  }

  out.push('## Package dependencies', '');
  if (config.layers?.length) {
    out.push(`Layers, from top to bottom: ${config.layers.map((l) => l.name).join(', ')}. A package may depend on its own layer and the ones below it.`, '');
  }
  out.push('Dashed edges are test-only or unused dependencies. Red edges break a rule.', '');
  mermaid(packageDiagram(model, config, violations));

  const withComponents = model.containers.filter((c) => model.components.filter((x) => x.package === c.name).length > 1);
  if (withComponents.length) {
    out.push('## Components', '');
    out.push('Folders inside each package and the imports between them.', '');
    for (const c of withComponents) {
      out.push(`### ${c.name}`, '');
      mermaid(componentDiagram(model, c.name, violations));
    }
  }

  out.push('## Rule check', '');
  if (!violations.length) {
    out.push('No violations.', '');
  } else {
    out.push('| Rule | Severity | Location | Message |', '| --- | --- | --- | --- |');
    for (const v of violations) {
      const loc = v.file ? `\`${v.file}${v.line ? `:${v.line}` : ''}\`` : '';
      out.push(`| ${v.rule} | ${v.severity} | ${loc} | ${cell(v.message)} |`);
    }
    out.push('');
  }
  return out.join('\n');
}

function cell(s: string): string {
  return s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
}
